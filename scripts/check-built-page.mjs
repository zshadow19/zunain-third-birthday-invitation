import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import sharp from "sharp";

const html = await readFile(".next/server/app/index.html", "utf8");
assert.match(html, /class="invitation-experience" data-state="full" data-enhanced="false"/);
assert.match(html, /class="card-frame"[^>]*id="invitation"[^>]*aria-hidden="false"/);
assert.equal((html.match(/class="invitation-artwork"/g) || []).length, 1);
assert.match(html, /class="extras-wrapper">/);
assert.doesNotMatch(html, /data-continue|View full invitation|View your invitation/);
assert.equal((html.match(/class="envelope-trigger"/g) || []).length, 1);
assert.equal((html.match(/data-replay=/g) || []).length, 1);
assert.equal((html.match(/<audio\b/g) || []).length, 1);
const audioTag = html.match(/<audio\b[^>]*>/)?.[0];
assert.match(audioTag, /src="\/audio\/playful-joyful-audio\.mp3"/);
assert.match(audioTag, /preload="none"/);
assert.doesNotMatch(audioTag, /autoplay/i);
assert.equal((html.match(/class="music-toggle"/g) || []).length, 1);
assert.match(html, /class="music-toggle" hidden/);
const music = await readFile("public/audio/playful-joyful-audio.mp3");
assert.ok(music.length > 0, "The production public music asset must exist");
assert.ok(music.subarray(0, 3).toString() === "ID3" || (music[0] === 0xff && (music[1] & 0xe0) === 0xe0), "The music asset must have an MP3 header");
assert.match(html, /2026-11-21T18:30:00\+06:00/);
assert.match(html, /https:\/\/www.google.com\/maps\/dir\/\?api=1/);
assert.match(html, /9th Floor, Lakeshore Heights, House 03, Road 126, Gulshan-1, Dhaka 1212, Bangladesh/);
assert.match(html, /destination=Lakeshore\+Heights%2C\+House\+03%2C\+Road\+126%2C\+Gulshan-1%2C\+Dhaka\+1212%2C\+Bangladesh/);
assert.match(html, /property="og:image"/);
assert.match(html, /name="twitter:card" content="summary_large_image"/);
assert.match(html, /rel="canonical"/);
const metadata = await sharp("public/social-preview.jpg").metadata();
assert.equal(metadata.width, 1200); assert.equal(metadata.height, 630);
const master = await readFile("public/dinosaur_jungle_birthday_invitation_artwork.png");
assert.equal(createHash("sha256").update(master).digest("hex"), "59a0a00edadde1d01d401a8d8a58dafd727129d83f66d2e292fc39d12f911ded");
console.log("Built HTML: one full accessible card, one envelope target, one Replay, event/directions and sharing metadata; no redundant navigation. Social dimensions and unchanged original artwork verified.");
console.log(`Music: one silent, non-preloaded audio element and one toggle; local MP3 present (${music.length} bytes).`);
